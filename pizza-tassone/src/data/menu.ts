  MENU_ITEMS.find(item => item.id === id);

export const getMenuItemsByCategory = (category: string): MenuItem[] =>
  MENU_ITEMS.filter(item => item.category === category && item.isAvailable);

export const getFeaturedPizzas = (): MenuItem[] =>
  MENU_ITEMS.filter(item =>
    item.category === 'pizza' &&
    item.tags.includes('beliebt') &&
    item.isAvailable
  ).slice(0, 6);

